const DICT = { zh: ZH, en: EN };
const LANG_KEY = "ops_lang";

export function lang() {
  // 优先用服务端返回的 preferred_lang（登录后），未登录或 localStorage 优先
  if (typeof window !== "undefined" && window.__USER_LANG__) return DICT[window.__USER_LANG__] ? window.__USER_LANG__ : "zh";
  const v = localStorage.getItem(LANG_KEY);
  return DICT[v] ? v : "zh";
}

export function setLang(v) {
  if (DICT[v]) {
    localStorage.setItem(LANG_KEY, v);
    if (typeof window !== "undefined") window.__USER_LANG__ = v;
  }
}

/** 缺词时：先回退当前语种（已无）→ zh → 兜底 fallback → key 名（绝不返回 undefined 造成空白）。 */
export function t(key, fallback) {
  const l = lang();
  return DICT[l]?.[key] ?? DICT.zh[key] ?? fallback ?? key;
}

/** 一次性把 data-i18n / data-i18n-title 属性节点换成当前语言的文案（外壳用）。 */
export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n, el.textContent); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle, el.title); });
}

/** 切换语言——刷新整页（最稳）。调用方负责把语言值写到 localStorage + 通知后端。 */
export async function applyLang(v) {
  setLang(v);
  location.reload();
}

/** 登录后用服务端返回的 preferred_lang 覆盖。 */
export function applyServerLang(v) {
  if (!DICT[v]) v = "zh";
  setLang(v);
  if (typeof window !== "undefined") window.__USER_LANG__ = v;
}
